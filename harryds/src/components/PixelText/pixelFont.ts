// 輔助函數：檢查字符是否支援
export const isCharacterSupported = (char: string): boolean => {
  return char.toUpperCase() in PIXEL_FONT;
};

// 輔助函數：取得字符的 pixel 數據
export const getCharacterPixelData = (char: string): PixelCharacter => {
  const upperChar = char.toUpperCase();
  return PIXEL_FONT[upperChar] || PIXEL_FONT[' '];
};

// 計算文字總寬度的函數
export const calculateTextWidth = (text: string): number => {
  return text.length * CHAR_WIDTH;
};
